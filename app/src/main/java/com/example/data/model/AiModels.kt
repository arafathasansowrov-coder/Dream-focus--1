package com.example.data.model

import java.util.UUID

/**
 * AI Model Provider options for the unified chatbot interface.
 */
enum class AiModelType(
    val id: String,
    val displayName: String,
    val shortName: String,
    val company: String,
    val badgeName: String,
    val description: String
) {
    GEMINI(
        id = "gemini",
        displayName = "Gemini 3.5 Flash",
        shortName = "Gemini",
        company = "Google DeepMind",
        badgeName = "Gemini 3.5",
        description = "Deep multimodal reasoning, math equations & academic solutions"
    ),
    CHATGPT(
        id = "chatgpt",
        displayName = "ChatGPT (GPT-4o)",
        shortName = "ChatGPT",
        company = "OpenAI",
        badgeName = "GPT-4o",
        description = "Pedagogical conversational clarity, step-by-step logic & coding tutor"
    )
}

/**
 * Message data class representing messages in the AI Chat.
 */
data class ChatMessage(
    val id: String = UUID.randomUUID().toString(),
    val text: String,
    val isUser: Boolean,
    val timestamp: Long = System.currentTimeMillis(),
    val isError: Boolean = false,
    val studyPlan: GeneratedStudyPlan? = null,
    val modelType: AiModelType = AiModelType.GEMINI,
    val aiAction: AiAppAction? = null
)

/**
 * Weekly productivity daily stats for Recharts-style data visualization.
 */
data class WeeklyProductivityDay(
    val dayName: String, // "Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"
    val dayIndex: Int, // 0..6
    val fullDate: String, // "Oct 12"
    val milestonesAchieved: Int,
    val routinesCompleted: Int,
    val focusMinutes: Int,
    val isToday: Boolean = false
)

/**
 * Weekly productivity aggregate summary.
 */
data class WeeklyProductivitySummary(
    val days: List<WeeklyProductivityDay>,
    val totalMilestonesAchieved: Int,
    val totalRoutinesCompleted: Int,
    val totalFocusHours: Float,
    val peakDayName: String,
    val disciplineRatePercent: Int
)

/**
 * Type of reminder/alarm selected by the user for routines and study tasks.
 */
enum class ReminderType(
    val displayName: String,
    val shortLabel: String,
    val description: String
) {
    PSYCHOLOGICAL_MESSAGE(
        displayName = "Psychological Nudge",
        shortLabel = "Mindset Nudge",
        description = "Motivational message, mental coaching & psychological reframing"
    ),
    DIRECT_ALARM(
        displayName = "Direct Audible Alarm",
        shortLabel = "Audible Alarm",
        description = "Direct audible alarm ringtone with persistent ringing, snooze & dismiss"
    ),
    BOTH(
        displayName = "Both Nudge + Alarm",
        shortLabel = "Dual Alert",
        description = "Gentle psychological preparation message followed by direct alarm"
    ),
    NONE(
        displayName = "Silent (Off)",
        shortLabel = "Silent",
        description = "No notification or alarm"
    )
}

/**
 * AI-Extracted routine suggestion from an uploaded schedule or timetable photo.
 */
data class AnalyzedRoutineSuggestion(
    val id: String = UUID.randomUUID().toString(),
    val title: String,
    val time: String = "08:00 AM", // "08:00 AM"
    val durationMinutes: Int = 45,
    val category: String = "Deep Work",
    var reminderType: ReminderType = ReminderType.PSYCHOLOGICAL_MESSAGE,
    var psychologicalTone: String = "Growth Mindset & Discipline",
    var isSelected: Boolean = true
)

/**
 * Task within an AI-generated Gamified Goal quest level.
 */
data class QuestTask(
    val id: String = UUID.randomUUID().toString(),
    val taskTitle: String,
    val xpValue: Int = 50,
    val isDone: Boolean = false
)

/**
 * Individual level stage in the RPG-style Gamified Goal Completer.
 */
data class GoalQuestLevel(
    val levelNumber: Int,
    val levelRank: String, // e.g. "Novice Initiate", "Apprentice Vanguard", "Adept Scholar", "Master Tactician", "Grandmaster Legend"
    val levelTitle: String,
    val description: String,
    val xpReward: Int,
    val tasks: List<QuestTask>,
    val bossTrialTitle: String,
    val bossTrialDescription: String,
    val isCompleted: Boolean = false,
    val isUnlocked: Boolean = false
)

/**
 * Complete RPG game progression for a goal.
 */
data class GamifiedGoalProgress(
    val goalId: Long,
    val goalTitle: String,
    val currentLevelNumber: Int = 1,
    val totalXp: Int = 120,
    val gems: Int = 45,
    val streakBonusMultiplier: Float = 1.25f,
    val playerTitle: String = "Apprentice Vanguard",
    val levels: List<GoalQuestLevel> = emptyList(),
    val unlockedPerks: List<String> = listOf("Novice Badge", "Focus Shield Rank I")
)

/**
 * Structured AI Study Plan generated by Gemini.
 */
data class GeneratedStudyPlan(
    val title: String,
    val targetSubject: String,
    val timeframe: String,
    val dailyHours: Float,
    val overview: String,
    val modules: List<PlanModule>,
    val suggestedRoutines: List<PlanRoutineItem>
)

data class PlanModule(
    val phase: String, // e.g. "Week 1: Fundamentals"
    val title: String,
    val milestones: List<String>,
    val tips: String = ""
)

data class PlanRoutineItem(
    val title: String,
    val suggestedTime: String, // e.g. "07:00 AM", "05:00 PM"
    val durationMinutes: Int,
    val category: String = "Deep Work"
)

